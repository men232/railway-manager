const (
	kindDBPassword = "db.password"
	dbTargetPrefix = "db:"

	stepPreflight = "preflight"
	stepDBPW      = "dbpw"
	stepDBVerify  = "dbverify"
)

// Sources of a new database password.
const (
	// SourceGenerate: a password generated by the app.
	SourceGenerate = "generate"
	// SourcePaste: a password the user pasted.
	SourcePaste = "paste"
	// SourceHand: the user already changed the password inside the
	// database; the run only writes Railway and checks the login.
	SourceHand = "hand"
	// SourceRevert: the variable's value set back into the database.
	SourceRevert = "revert"
)

var sources = []string{SourceGenerate, SourcePaste, SourceHand, SourceRevert}

// errNonASCIIPostgres is the refusal of a typed Postgres password the SCRAM
// verifier cannot carry (dbops computes it without SASLprep).
var errNonASCIIPostgres = errors.New("Postgres password must be ASCII here (no SASLprep) · use g to generate")

// errReferenceInPassword is the refusal of a typed password holding "${{":
// Railway would read the variable written with it as a reference.
var errReferenceInPassword = errors.New("a password cannot hold ${{ (Railway reads it as a reference)")

// CheckTypedPassword refuses a typed password (pasted, entered as changed
// by hand, a KEYFILE) Railway cannot store as it is: one holding "${{". The
// paste prompts and Validate share it. The error never holds the value.
func CheckTypedPassword(value string) error {
	if strings.Contains(value, "${{") {
		return errReferenceInPassword
	}
	return nil
}

// CheckPastedPassword refuses a pasted (or reverted) password the database
// kind or Railway cannot take: CheckTypedPassword's, and a Postgres password
// with non-ASCII characters. The paste prompt and Validate share it. The
// error never holds the value.
func CheckPastedPassword(dbKind, value string) error {
	if err := CheckTypedPassword(value); err != nil {
		return err
	}
	if dbKind != "postgres" {
		return nil
	}
	for i := 0; i < len(value); i++ {
		if value[i] >= 0x80 {
			return errNonASCIIPostgres
		}
	}
	return nil
}

// dbInfo is how the steps reach a database, resolved when the change is
// made (the change is self-contained after). It holds no secret.
type dbInfo struct {
	Kind     string `json:"kind"`
	Port     int    `json:"port"`
	RootUser string `json:"rootUser"`
	// Members are the replica members besides the owner (Mongo).
	Members []domain.Place `json:"members,omitempty"`
	// PrivateHost is the owner's RAILWAY_PRIVATE_DOMAIN: a Postgres login
	// that proves a password goes there.
	PrivateHost string `json:"privateHost,omitempty"`
	// After are the places whose redeploys the verify waits for: the
	// row's URL places and copies.
	After []domain.Place `json:"after,omitempty"`
}

func (i dbInfo) valid() error {
	if rotation.RootVar(i.Kind) == "" {
		return errors.New("unknown database kind")
	}
	if i.Port <= 0 || i.Port > 65535 {
		return errors.New("bad port")
	}
	if i.RootUser == "" || strings.HasPrefix(i.RootUser, "@") {
		return errors.New("root user unknown")
	}
	for _, p := range slices.Concat(i.Members, i.After) {
		if p.EnvID == "" || p.ServiceID == "" {
			return errors.New("bad place")
		}
	}
	if i.Kind == "postgres" {
		if _, _, err := dbops.Forward(i.Kind, i.Port, i.PrivateHost); err != nil {
			return err
		}
	}
	return nil
}

// dbPasswordNew is the New of a db.password change. It is a secret. Value
// is the password the database gets. For a revert,
// Value is the own variable's current value and Login the password the
// abandoned run gave the database, which the change logs in with first.
type dbPasswordNew struct {
	Source string `json:"source"`
	Value  string `json:"value"`
	Login  string `json:"login,omitempty"`
	DB     dbInfo `json:"db"`
	// AuthDB is a Mongo user's database (rotation.PasswordRow.AuthDB):
	// another database's user of the same name is another user. "" is
	// admin, as for a change made before it was kept.
	AuthDB string `json:"authDB,omitempty"`
}

// infoOf resolves a row's database for its steps.
func infoOf(s *store.Store, row rotation.PasswordRow) dbInfo {
	db := row.DB
	info := dbInfo{
		Kind: db.Kind, Port: db.Port, RootUser: db.RootUser, Members: db.Members,
		PrivateHost: s.SystemVar(db.Owner.EnvID, db.Owner.ServiceID, "RAILWAY_PRIVATE_DOMAIN"),
	}
	seen := map[string]bool{db.Owner.Key(): true}
	for _, u := range slices.Concat(row.URLs, row.Copies) {
		if u.Mode != rotation.URLRewrite && u.Mode != rotation.URLFollows {
			continue
		}
		if p := u.Loc.Place; !p.Shared() && !seen[p.Key()] {
			seen[p.Key()] = true
			info.After = append(info.After, p)
		}
	}
	return info
}

// DBPassword makes the db.password change of a password row (a root or a
// user, not a KEYFILE): place the database owner, target the user, group
// the row's. A root change's base is its own variable's state. The value is
// a secret; source is one of the Source constants but SourceRevert
// (DBPasswordRevert).
func DBPassword(s *store.Store, row rotation.PasswordRow, source, value string, now time.Time) (changeset.Change, error) {
	if source == SourceRevert {
		return changeset.Change{}, errors.New("a revert is made with DBPasswordRevert")
	}
	return newDBPassword(s, row, dbPasswordNew{Source: source, Value: value}, now)
}

// DBPasswordRevert makes the revert of a root password row: the database is
// set back to its own variable's current value, logging in with login, the
// password the abandoned run set (then with the variable's value, should the
// database still hold it). Both are secrets.
func DBPasswordRevert(s *store.Store, row rotation.PasswordRow, login string, now time.Time) (changeset.Change, error) {
	if !row.Root || row.KeyFile {
		return changeset.Change{}, errors.New("only a root password is reverted")
	}
	v := s.Variable(domain.LocationID(row.DB.Owner.EnvID, row.DB.Owner.ServiceID, rotation.RootVar(row.DB.Kind)))
	if v == nil || !v.Literal || v.Sealed {
		return changeset.Change{}, errors.New("the database's own password variable cannot be read")
	}
	return newDBPassword(s, row, dbPasswordNew{Source: SourceRevert, Value: v.Unrendered, Login: login}, now)
}

// PasswordValue is the source and the new password a db.password change
// carries, for a screen deciding the password's places again; false for
// another kind or a New without a value. The value is a secret.
func PasswordValue(c changeset.Change) (source, value string, ok bool) {
	if c.Kind != kindDBPassword {
		return "", "", false
	}
	var nv dbPasswordNew
	if err := json.Unmarshal(c.New, &nv); err != nil || nv.Value == "" {
		return "", "", false
	}
	return nv.Source, nv.Value, true
}

// RevertKeeps reports the changes whose value an abandoned run keeps, for
// apply.Runs.KeepAbandoned: a database password, which a revert of the
// stalled run logs in with.
func RevertKeeps(c changeset.Change) bool { return c.Kind == kindDBPassword }

// PasswordFingerprint is the fingerprint (rotation.Fingerprint) of the new
// password a db.password change sets, for apply.Runs.Fingerprint; "" for
// another kind, a change without a value, or a revert (its value is the
// password Railway already holds).
func PasswordFingerprint(c changeset.Change) string {
	source, value, ok := PasswordValue(c)
	if !ok || source == SourceRevert {
		return ""
	}
	return rotation.Fingerprint(value)
}

func newDBPassword(s *store.Store, row rotation.PasswordRow, nv dbPasswordNew, now time.Time) (changeset.Change, error) {
	if row.KeyFile {
		return changeset.Change{}, errors.New("a KEYFILE row has no password")
	}
	if row.Problem != "" {
		return changeset.Change{}, errors.New(row.Problem)
	}
	nv.DB = infoOf(s, row)
	nv.AuthDB = row.AuthDB
	raw, err := json.Marshal(nv)
	if err != nil {
		return changeset.Change{}, err
	}
	c := changeset.Change{
		ID: changeset.NewID(), Kind: kindDBPassword, Place: row.DB.Owner, Target: row.User,
		New: raw, Group: row.Key, Created: now,
	}
	if row.Root {
		c.Base = baseOf(s, row.DB.Owner, rotation.RootVar(row.DB.Kind))
	}
	if err := (dbPasswordKind{}).Validate(s, c); err != nil {
		return changeset.Change{}, err
	}
	return c, nil
}

// decodeDBPassword decodes a db.password New strictly and checks it against
// the change: a known source, a value, a reachable database, a group naming
// the place and user. Errors never hold the value.
func decodeDBPassword(c changeset.Change) (dbPasswordNew, error) {
	var nv dbPasswordNew
	if err := strictDecode(c.New, &nv); err != nil {
		return nv, errors.New("db.password: bad change data")
	}
	if !slices.Contains(sources, nv.Source) {
		return nv, errors.New("db.password: bad change data: unknown source")
	}
	if nv.Value == "" {
		return nv, errors.New("db.password: no new password")
	}
	if err := nv.DB.valid(); err != nil {
		return nv, fmt.Errorf("db.password: bad change data: %w", err)
	}
	if nv.AuthDB != "" && nv.DB.Kind != "mongo" {
		return nv, errors.New("db.password: bad change data: an auth database is Mongo's")
	}
	if c.Place.Shared() || c.Target == "" || strings.HasPrefix(c.Target, "@") {
		return nv, errors.New("db.password: bad change data: no user")
	}
	if c.Group != rotation.DBGroupKey(c.Place.Key(), c.Target) {
		return nv, errors.New("db.password: bad change data: group")
	}
	switch nv.Source {
	case SourcePaste, SourceRevert:
		if err := CheckPastedPassword(nv.DB.Kind, nv.Value); err != nil {
			return nv, err
		}
	case SourceHand:
		// The database's own password: any characters, but no reference.
		if err := CheckTypedPassword(nv.Value); err != nil {
			return nv, err
		}
	}
	switch {
	case nv.Source == SourceRevert && (nv.Login == "" || nv.Login == nv.Value):
		return nv, errors.New("db.password: a revert needs the password to log in with")
	case nv.Source == SourceRevert && !nv.isRoot(c):
		return nv, errors.New("db.password: only a root password is reverted")
	case nv.Source != SourceRevert && nv.Login != "":
		return nv, errors.New("db.password: bad change data: login")
	}
	return nv, nil
}

// isRoot reports whether the change's user is its database's root.
func (nv dbPasswordNew) isRoot(c changeset.Change) bool { return c.Target == nv.DB.RootUser }

// dbPasswordKind is db.password: a password changed inside a database
// through an SSH tunnel.
type dbPasswordKind struct{}

func (dbPasswordKind) Name() string { return kindDBPassword }

func (dbPasswordKind) ValidateData(c changeset.Change) error {
	_, err := decodeDBPassword(c)
	return err
}

// Validate is ValidateData, and for a root that its own variable is a
// literal the new password differs from.
func (dbPasswordKind) Validate(s *store.Store, c changeset.Change) error {
	nv, err := decodeDBPassword(c)
	if err != nil {
		return err
	}
	if !nv.isRoot(c) {
		if c.Base.Fingerprint != "" && c.Base.Fingerprint == dbFingerprint(c, nv) {
			return errors.New("the new password is the current one")
		}
		return nil
	}
	name := rotation.RootVar(nv.DB.Kind)
	v := s.Variable(domain.LocationID(c.Place.EnvID, c.Place.ServiceID, name))
	switch {
	case v == nil:
		return fmt.Errorf("%s not found at the database", name)
	case !v.Literal:
		return fmt.Errorf("%s is not a literal value", name)
	case v.Sealed:
		return fmt.Errorf("%s is sealed: its current value cannot be read", name)
	case nv.Source == SourceRevert:
		// A revert sets the database back to the variable's value.
		if v.Fingerprint != dbFingerprint(c, nv) {
			return fmt.Errorf("%s changed since the revert was made", name)
		}
	case v.Fingerprint == dbFingerprint(c, nv):
		return errors.New("the new password is the current one")
	}
	return nil
}

// dbFingerprint is the fingerprint the new password would have in the
// database's own variable (for a user, under the user's name).
func dbFingerprint(c changeset.Change, nv dbPasswordNew) string {
	name := c.Target
	if nv.isRoot(c) {
		name = rotation.RootVar(nv.DB.Kind)
	}
	return domain.Fingerprint(name, nv.Value, false, true, c.Place.EnvID, c.Place.ServiceID)
}

func (dbPasswordKind) IsNoop(changeset.Change) bool { return false }
func (dbPasswordKind) Secret(changeset.Change) bool { return true }
func (dbPasswordKind) Reopen() bool                 { return true }

func (dbPasswordKind) Overlay(c changeset.Change) apply.Overlay {
	var nv dbPasswordNew
	_ = json.Unmarshal(c.New, &nv)
	switch nv.Source {
	case SourceHand:
		return apply.Overlay{Short: "changed by hand", Long: "changed by hand", Tone: "danger"}
	case SourceRevert:
		return apply.Overlay{Short: "↶ revert database password", Long: "↶ revert database password", Tone: "warn"}
	}
	s := fmt.Sprintf("→ new password (%d chars)", utf8.RuneCountInString(nv.Value))
	return apply.Overlay{Short: s, Long: s, Tone: "new"}
}

// dbWrite names a database user's password as a write target.
func dbWrite(owner domain.Place, user string) string {
	return dbTargetPrefix + owner.Key() + ":" + user
}

func (dbPasswordKind) Writes(c changeset.Change) []string {
	return []string{dbWrite(c.Place, c.Target)}
}

// Reads: a user's change logs in as the root.
func (dbPasswordKind) Reads(c changeset.Change) []string {
	var nv dbPasswordNew
	if err := json.Unmarshal(c.New, &nv); err != nil || nv.DB.RootUser == "" || nv.isRoot(c) {
		return nil
	}
	return []string{dbWrite(c.Place, nv.DB.RootUser)}
}

func (dbPasswordKind) Check(context.Context, *apply.Env, changeset.Change) (apply.Drift, error) {
	return apply.DriftNone, nil
}
func (dbPasswordKind) Patch(changeset.Change) (map[string]any, bool)           { return nil, false }
func (dbPasswordKind) Redeploys(*store.Store, changeset.Change) []domain.Place { return nil }

// OwnSteps: preflight → dbpw → dbverify; a password changed by hand has
// no dbpw. The writes that require the change depend on the step serving
// it: dbpw, or preflight for hand.
func (dbPasswordKind) OwnSteps(c changeset.Change) []apply.Step {
	var nv dbPasswordNew
	_ = json.Unmarshal(c.New, &nv)
	hand := nv.Source == SourceHand
	pre := &dbStep{phase: stepPreflight, c: c}
	steps := []apply.Step{pre}
	if hand {
		pre.serves = true
	} else {
		steps = append(steps, &dbStep{phase: stepDBPW, c: c, serves: true})
	}
	return append(steps, &dbStep{phase: stepDBVerify, c: c})
}

var (
	_ apply.DataValidator = dbPasswordKind{}
	_ apply.Reopener      = dbPasswordKind{}
)

// dbStepKey is "<phase>:<owner place key>:<user>".
func dbStepKey(phase string, owner domain.Place, user string) string {
	return phase + ":" + owner.Key() + ":" + user
}

// dbStep is one step of a db.password change (preflight, dbpw, dbverify)
// or the verify of a db.keyfile change.
type dbStep struct {
	phase  string
	c      changeset.Change
	serves bool
}

func (s *dbStep) Key() string  { return dbStepKey(s.phase, s.c.Place, s.c.Target) }
func (s *dbStep) Lock() string { return s.c.Place.Key() }

func (s *dbStep) Serves() []string {
	if s.serves {
		return []string{s.c.ID}
	}
	return nil
}

func (s *dbStep) Label() string {
	what := map[string]string{stepPreflight: "pre-flight", stepDBPW: "change password", stepDBVerify: "verify"}[s.phase]
	return what + " " + text.Sanitize(s.c.Target) + " at " + s.c.Place.Key()
}

// Reopenable: only dbpw acts again while a write requiring it is pending.
func (s *dbStep) Reopenable() bool { return s.phase == stepDBPW }

func (s *dbStep) Deps() []string {
	if s.c.Kind == kindDBKeyFile {
		info, _ := decodeKeyFile(s.c)
		return redeployKeys(slices.Concat([]domain.Place{s.c.Place}, info.Members))
	}
	var nv dbPasswordNew
	_ = json.Unmarshal(s.c.New, &nv)
	switch s.phase {
	case stepPreflight:
		if nv.DB.RootUser == "" || nv.isRoot(s.c) {
			return nil
		}
		// A user's change logs in as root: after the root's change when it
		// is in the run. Absent steps are dropped by Compile.
		return []string{
			dbStepKey(stepDBPW, s.c.Place, nv.DB.RootUser),
			dbStepKey(stepPreflight, s.c.Place, nv.DB.RootUser),
		}
	case stepDBPW:
		deps := []string{dbStepKey(stepPreflight, s.c.Place, s.c.Target)}
		if nv.DB.RootUser != "" && !nv.isRoot(s.c) {
			// Changed by the root: after the root's own change.
			deps = append(deps, dbStepKey(stepDBPW, s.c.Place, nv.DB.RootUser))
		}
		return deps
	}
	before := stepDBPW
	if nv.Source == SourceHand {
		before = stepPreflight
	}
	return append([]string{dbStepKey(before, s.c.Place, s.c.Target)}, redeployKeys(nv.DB.After)...)
}

func redeployKeys(ps []domain.Place) []string {
	out := make([]string, 0, len(ps))
	for _, p := range ps {
		out = append(out, "redeploy:"+p.Key())
	}
	return out
}

// Run acts once per attempt. A done record is a rebuild: these steps add
// no steps, so there is nothing to do.
func (s *dbStep) Run(ctx context.Context, env *apply.Env, prior apply.StepRecord) (apply.Result, error) {
	if prior.Status == apply.StatusDone {
		return apply.Result{}, nil
	}
	if env.Proc == nil {
		return apply.Result{}, errors.New("no process runner")
	}
	// Tunnels an earlier attempt, or a sibling step that finished, could
	// not stop.
	reapTunnels(env, s.siblingKeys()...)
	if s.c.Kind == kindDBKeyFile {
		return s.verifyKeyFile(ctx, env)
	}
	nv, err := decodeDBPassword(s.c)
	if err != nil {
		return apply.Result{}, err
	}
	switch s.phase {
	case stepPreflight:
		return s.preflight(ctx, env, nv)
	case stepDBPW:
		return s.change(ctx, env, nv)
	}
	return s.verify(ctx, env, nv)
}

func (s *dbStep) done() apply.Result {
	return apply.Result{Outcomes: map[string]apply.Outcome{s.c.ID: {Status: "done"}}}
}

func (s *dbStep) target(nv dbPasswordNew) dbops.Target {
	return dbops.Target{
		DB:   rotation.DB{Key: s.c.Place.Key(), Kind: nv.DB.Kind, RootUser: nv.DB.RootUser, Port: nv.DB.Port, Owner: s.c.Place, Members: nv.DB.Members},
		User: s.c.Target, Root: nv.isRoot(s.c), AuthDB: nv.AuthDB,
	}
}

// clientNames are the programs Missing checks, by kind.
var clientNames = map[string]string{"mongo": "mongosh", "postgres": "psql", "redis": "redis-cli", "ssh": "ssh"}

// clientsPresent refuses a run when ssh or the database's client is not
// installed, naming the install command.
func clientsPresent(env *apply.Env, kind string) error {
	for _, k := range []string{"ssh", kind} {
		install, missing, err := dbops.Missing(env.Proc, k)
		if err != nil {
			return err
		}
		if missing {
			return fmt.Errorf("%s is not installed · %s", clientNames[k], install)
		}
	}
	return nil
}

// preflight proves, writing nothing, that the change can run: the clients
// are installed, every redeploy target has a deployment, no write of the
// group drifted (checkGroupWrites), a tunnel opens, and the admin logs in
// (Mongo: on the writable primary) and finds the user (dbops.Check) — for a
// password changed by hand, that the database takes the new password.
func (s *dbStep) preflight(ctx context.Context, env *apply.Env, nv dbPasswordNew) (apply.Result, error) {
	if err := clientsPresent(env, nv.DB.Kind); err != nil {
		return apply.Result{}, err
	}
	if err := redeployable(ctx, env, s.c.Group); err != nil {
		return apply.Result{}, err
	}
	if err := checkGroupWrites(ctx, env, s.c); err != nil {
		return apply.Result{}, err
	}
	var creds dbops.Creds
	if nv.Source != SourceHand {
		var err error
		if creds, err = s.creds(ctx, env, nv); err != nil {
			return apply.Result{}, err
		}
	}
	err := withTunnels(ctx, env, s.Key(), s.c.Place, nv.DB, false, func(tuns []dbops.Tunnel) error {
		if nv.Source == SourceHand {
			if err := loginAny(ctx, env, s.target(nv), tuns, nv.Value); err != nil {
				return fmt.Errorf("the database does not accept the new password: %w", err)
			}
			// The database holds the new password: a run that fails from
			// here on is stalled like one past its dbpw.
			return env.MarkActed(s.Key())
		}
		_, err := dbops.Check(ctx, env.Proc, s.target(nv), tuns, creds)
		return err
	})
	if err != nil {
		return apply.Result{}, err
	}
	if s.serves {
		return s.done(), nil
	}
	return apply.Result{}, nil
}

// redeployable checks, writing nothing, that every redeploy target of the
// group (the run's frozen actions serving a change of it, env.Actions) has
// a latest deployment to redeploy: one is listed and the newest is not
// REMOVED. A crashed or failed one counts: the redeploy may fix it.
func redeployable(ctx context.Context, env *apply.Env, group string) error {
	ids := map[string]bool{}
	for _, c := range env.Changes {
		if c.Group == group {
			ids[c.ID] = true
		}
	}
	for _, p := range groupRedeploys(env.Actions, ids) {
		ds, err := env.API.Deployments(ctx, p.EnvID, p.ServiceID)
		if err != nil {
			return err
		}
		if len(ds) == 0 || ds[0].Status == "REMOVED" {
			svc := p.ServiceID
			if env.Store != nil {
				svc = text.Sanitize(env.Store.EnvName(p.EnvID)) + " · " + text.Sanitize(env.Store.ServiceName(p.ServiceID))
			}
			return errors.New(svc + " has no deployment to redeploy · deploy it once, then run apply again")
		}
	}
	return nil
}

// change sets the password inside the database. It marks the step acted
// before the change is sent. A reopened step finds the database maybe
// holding the new password already: a root change logs in with the
// current password, then the new one (dbops.SetPassword).
func (s *dbStep) change(ctx context.Context, env *apply.Env, nv dbPasswordNew) (apply.Result, error) {
	if err := groupWritable(env, s.c); err != nil {
		return apply.Result{}, err
	}
	creds, err := s.creds(ctx, env, nv)
	if err != nil {
		return apply.Result{}, err
	}
	err = withTunnels(ctx, env, s.Key(), s.c.Place, nv.DB, false, func(tuns []dbops.Tunnel) error {
		if err := env.MarkActed(s.Key()); err != nil {
			return err
		}
		_, err := dbops.SetPassword(ctx, env.Proc, s.target(nv), tuns, creds)
		return err
	})
	if err != nil {
		return apply.Result{}, err
	}
	return s.done(), nil
}

// groupWritable asks the write guard for every environment a database
// password change writes to: its database's, and those of its group's
// frozen changes (keeps excepted). Prepare vets the same; a resumed run asks
// again, as an environment may have left the write environments since, and
// a database must not take a password its variables cannot follow.
func groupWritable(env *apply.Env, c changeset.Change) error {
	if err := env.API.CheckWrite(c.Place.EnvID); err != nil {
		return err
	}
	for _, o := range env.Changes {
		if o.Group != c.Group || o.Kind == kindKeep {
			continue
		}
		if err := env.API.CheckWrite(o.Place.EnvID); err != nil {
			return err
		}
	}
	return nil
}

// verify logs in with the new password.
func (s *dbStep) verify(ctx context.Context, env *apply.Env, nv dbPasswordNew) (apply.Result, error) {
	err := withTunnels(ctx, env, s.Key(), s.c.Place, nv.DB, false, func(tuns []dbops.Tunnel) error {
		if err := loginAny(ctx, env, s.target(nv), tuns, nv.Value); err != nil {
			return fmt.Errorf("the database does not accept the new password: %w", err)
		}
		return nil
	})
	return apply.Result{}, err
}

// creds are the passwords of a change or its pre-flight: a root logs in as
// itself with the current password from Railway, then the new one; a user
// is changed by the root (adminPassword).
func (s *dbStep) creds(ctx context.Context, env *apply.Env, nv dbPasswordNew) (dbops.Creds, error) {
	if nv.isRoot(s.c) && nv.Source == SourceRevert {
		// The database holds the abandoned run's password (Login); the
		// variable still holds the value it goes back to (Value).
		return dbops.Creds{AdminUser: s.c.Target, Current: nv.Login, New: nv.Value}, nil
	}
	if nv.isRoot(s.c) {
		cur, err := currentRoot(ctx, env, s.c.Place, nv.DB.Kind)
		if err != nil {
			return dbops.Creds{}, err
		}
		return dbops.Creds{AdminUser: s.c.Target, Current: cur, New: nv.Value}, nil
	}
	admin, err := s.adminPassword(ctx, env, nv)
	if err != nil {
		return dbops.Creds{}, err
	}
	return dbops.Creds{AdminUser: nv.DB.RootUser, Admin: admin, New: nv.Value}, nil
}

// adminPassword is the root password a user's step logs in with: the new root
// once the root's password changed in this run (its dbpw done, or changed by
// hand), the current root from Railway otherwise.
func (s *dbStep) adminPassword(ctx context.Context, env *apply.Env, nv dbPasswordNew) (string, error) {
	group := rotation.DBGroupKey(s.c.Place.Key(), nv.DB.RootUser)
	for _, rc := range env.Changes {
		if rc.Kind != kindDBPassword || rc.Group != group {
			continue
		}
		root, err := decodeDBPassword(rc)
		if err != nil {
			break
		}
		if root.Source == SourceHand ||
			env.Journal != nil && env.Journal.Step(dbStepKey(stepDBPW, s.c.Place, nv.DB.RootUser)).Status == apply.StatusDone {
			return root.Value, nil
		}
	}
	return currentRoot(ctx, env, s.c.Place, nv.DB.Kind)
}

// currentRoot reads the database's own root password variable from
// Railway, fresh.
func currentRoot(ctx context.Context, env *apply.Env, owner domain.Place, kind string) (string, error) {
	name := rotation.RootVar(kind)
	env.Forget(owner)
	vars, err := env.ReadPlace(ctx, owner)
	if err != nil {
		return "", fmt.Errorf("read %s: %w", name, err)
	}
	v := vars[name]
	switch {
	case v == "":
		return "", fmt.Errorf("%s not found at the database", name)
	case len(domain.ParseReferences(v)) > 0:
		return "", fmt.Errorf("%s is not a literal value", name)
	}
	return v, nil
}

// loginAny logs in through the tunnels in turn until one takes password
// (Mongo members; one tunnel otherwise).
func loginAny(ctx context.Context, env *apply.Env, t dbops.Target, tuns []dbops.Tunnel, password string) error {
	var errs []error
	for i := range tuns {
		err := dbops.Login(ctx, env.Proc, t, &tuns[i], password)
		if err == nil {
			return nil
		}
		if ctx.Err() != nil {
			return err
		}
		if n := tuns[i].Member; n > 0 {
			err = fmt.Errorf("member %d: %w", n, err)
		} else if len(tuns) > 1 {
			err = fmt.Errorf("member %d: %w", i+1, err)
		}
		errs = append(errs, err)
	}
	return errors.Join(errs...)
}

// tunnelRecord is a tunnel journaled in StepRecord.Data so a later run can
// reap it. It is never a secret.
type tunnelRecord struct {
	Socket string `json:"socket"`
	Pid    int    `json:"pid"`
}

// tunnelData is a db step's journal Data: the tunnels not known stopped,
// and a warning when some could not be reaped.
type tunnelData struct {
	Tunnels []tunnelRecord `json:"tunnels,omitempty"`
	Warning string         `json:"warning,omitempty"`
	// Untrusted is the ssh host the step's last attempt would not connect
	// to, and its keys (UntrustedHost).
	Untrusted *dbops.HostKeys `json:"untrusted,omitempty"`
}

// UntrustedHost is the ssh host a database step's last attempt would not
// connect to, its key not trusted yet, with the keys it presented: the Run
// screen shows their fingerprints and trusts them on the operator's word.
func UntrustedHost(rec apply.StepRecord) (dbops.HostKeys, bool) {
	var d tunnelData
	if json.Unmarshal(rec.Data, &d) != nil || d.Untrusted == nil {
		return dbops.HostKeys{}, false
	}
	return *d.Untrusted, true
}

// saveUntrusted journals hk as the step's untrusted host, keeping its
// tunnels.
func saveUntrusted(env *apply.Env, key string, hk dbops.HostKeys) error {
	if env.Journal == nil {
		return nil
	}
	rec := env.Journal.Step(key)
	var d tunnelData
	_ = json.Unmarshal(rec.Data, &d)
	d.Untrusted = &hk
	raw, err := json.Marshal(d)
	if err != nil {
		return err
	}
	rec.Data = raw
	return env.Journal.Set(key, rec)
}

func readTunnels(env *apply.Env, key string) []tunnelRecord {
	var d tunnelData
	if env.Journal != nil {
		_ = json.Unmarshal(env.Journal.Step(key).Data, &d)
	}
	return d.Tunnels
}

// saveTunnels journals recs as the step's tunnels; warn adds the warning
// that some could not be reaped.
func saveTunnels(env *apply.Env, key string, recs []tunnelRecord, warn bool) error {
	if env.Journal == nil {
		return nil
	}
	d := tunnelData{Tunnels: recs}
	if warn && len(recs) > 0 {
		d.Warning = fmt.Sprintf("%d ssh tunnel(s) could not be stopped · reaped again on the next attempt; check for a stray ssh -L", len(recs))
	}
	var raw json.RawMessage
	if len(recs) > 0 {
		var err error
		if raw, err = json.Marshal(d); err != nil {
			return err
		}
	}
	rec := env.Journal.Step(key)
	rec.Data = raw
	return env.Journal.Set(key, rec)
}

// reapRecords reaps each record on its own (dbops.Reap signals only a pid
// whose command line still carries our forward) and returns those it could
// not handle.
func reapRecords(env *apply.Env, recs []tunnelRecord) []tunnelRecord {
	var left []tunnelRecord
	for _, r := range recs {
		if err := dbops.Reap(env.Proc, []dbops.Tunnel{{Socket: r.Socket, Pid: r.Pid}}); err != nil {
			left = append(left, r)
		}
	}
	return left
}

// reapTunnels reaps the tunnels journaled on keys (the steps of one
// change: an earlier attempt of this step, or a sibling step that finished
// with a tunnel it could not stop). What Reap could not handle stays
// journaled with a warning; it never fails the step.
func reapTunnels(env *apply.Env, keys ...string) {
	for _, k := range keys {
		recs := readTunnels(env, k)
		if len(recs) == 0 {
			continue
		}
		left := reapRecords(env, recs)
		_ = saveTunnels(env, k, left, true)
	}
}

// siblingKeys are the keys of every step of the step's change.
func (s *dbStep) siblingKeys() []string {
	return []string{
		dbStepKey(stepPreflight, s.c.Place, s.c.Target),
		dbStepKey(stepDBPW, s.c.Place, s.c.Target),
		dbStepKey(stepDBVerify, s.c.Place, s.c.Target),
	}
}

// tunnelPlaces are the places a database is reached at: the owner, and for
// Mongo every member (the change looks for the writable primary).
func tunnelPlaces(owner domain.Place, info dbInfo) []domain.Place {
	if info.Kind == "mongo" {
		return slices.Concat([]domain.Place{owner}, info.Members)
	}
	return []domain.Place{owner}
}

// openTunnel opens the tunnel to one place, journaling it as soon as ssh
// starts, before anything waits on it.
func openTunnel(ctx context.Context, env *apply.Env, key string, p, owner domain.Place, info dbInfo) (*dbops.Tunnel, error) {
	userHost, err := dbops.SSHTarget(ctx, env.Proc, p.ProjectID, p.EnvID, p.ServiceID)
	if err != nil {
		return nil, err
	}
	host := ""
	if p == owner {
		host = info.PrivateHost
	}
	remote, socket, err := dbops.Forward(info.Kind, info.Port, host)
	if err != nil {
		return nil, err
	}
	return dbops.Open(ctx, env.Proc, env.KnownHosts, userHost, info.Port, remote, socket, func(t dbops.Tunnel) error {
		return saveTunnels(env, key, append(readTunnels(env, key), tunnelRecord{Socket: t.Socket, Pid: t.Pid}), false)
	})
}

// withTunnels opens a tunnel to every place of the database and runs f
// with them. With every false (a Mongo change or login), a member whose
// tunnel fails is left out as long as one opens: the writable primary may
// be among the others; its failure is added to f's. Afterwards it closes
// the tunnels, reaps any whose close failed (and any whose open failed
// after ssh started) and keeps journaled, with a warning, only those that
// still could not be stopped.
func withTunnels(ctx context.Context, env *apply.Env, key string, owner domain.Place, info dbInfo, every bool,
	f func([]dbops.Tunnel) error) (err error) {
	var open []*dbops.Tunnel
	defer func() {
		closed := map[tunnelRecord]bool{}
		for _, t := range open {
			if t.Close() == nil {
				closed[tunnelRecord{Socket: t.Socket, Pid: t.Pid}] = true
			}
		}
		left := slices.DeleteFunc(readTunnels(env, key), func(r tunnelRecord) bool { return closed[r] })
		if len(left) > 0 {
			left = reapRecords(env, left)
		}
		err = errors.Join(err, saveTunnels(env, key, left, true))
		if ue := (*dbops.UntrustedHostError)(nil); errors.As(err, &ue) {
			err = errors.Join(err, saveUntrusted(env, key, ue.HostKeys))
		}
	}()
	places := tunnelPlaces(owner, info)
	var failed []error
	number := map[*dbops.Tunnel]int{} // 1-based place index
	for i, p := range places {
		t, err := openTunnel(ctx, env, key, p, owner, info)
		if err != nil {
			if every || len(places) == 1 || ctx.Err() != nil {
				return err
			}
			failed = append(failed, fmt.Errorf("member %d: %w", i+1, err))
			continue
		}
		number[t] = i + 1
		open = append(open, t)
	}
	if len(open) == 0 {
		return errors.Join(failed...)
	}
	tuns := make([]dbops.Tunnel, len(open))
	for i, t := range open {
		tuns[i] = *t
		if len(failed) > 0 {
			tuns[i].Member = number[t] // errors name places, not positions
		}
	}
	if err := f(tuns); err != nil {
		return errors.Join(append([]error{err}, failed...)...)
	}
	return nil
}
